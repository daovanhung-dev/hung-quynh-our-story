import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { scanMemories } from './lib/memory-scanner.mjs';

const { memories, errors } = await scanMemories();

if (errors.length > 0) {
  console.error('\nKhông thể generate memory manifest vì dữ liệu chưa hợp lệ:\n');
  for (const error of errors) console.error(`  - ${error}`);
  process.exit(1);
}

const outputPath = path.join(process.cwd(), 'src', 'app', 'generated', 'memories.generated.ts');
await mkdir(path.dirname(outputPath), { recursive: true });

const source = `import type { Memory } from '../core/models/memory.model';\n\n` +
  `// AUTO-GENERATED by scripts/generate-memory-index.mjs\n` +
  `// Do not edit this file manually.\n` +
  `export const MEMORIES: readonly Memory[] = ${JSON.stringify(memories, null, 2)};\n`;

await writeFile(outputPath, source, 'utf8');
console.log(`Generated ${path.relative(process.cwd(), outputPath)} with ${memories.length} memories.`);
